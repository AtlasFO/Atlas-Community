HIVES = ("SYSTEM", "SOFTWARE", "SAM", "SECURITY")
BATCH = Path(__file__).resolve().parents[1] / "share" / ".common" / "atlas_baseline.reb"
OUT_DIR = "analysis/baseline"
PROFILE_ROOTS = ("Users", "Documents and Settings")
_CONFIG_TAIL = ("windows", "system32", "config")
_DIRTY_RE = re.compile(r"(?i)dirty|transaction log|replay")
_SAM_USER_RE = re.compile(r"Username:\s*(.+?)\s+Id:\s*(\d+)")
_SAM_DATES_RE = re.compile(r"Created:\s*([\d-]+ [\d:.]+)?\s*Last login:\s*([\d-]+ [\d:.]+)?")
_UNINSTALL_RE = re.compile(r"DisplayName:\s*(.*?)\s*DisplayVersion:\s*(.*?)\s*Publisher:\s*(.*?)(?:\s*InstallDate:\s*(\S*))?\s*$")
# The time zone plugin can print the key name with a duplicated tail; the
# name ends at its first "Time" word ("W. Europe Standard Time").
_ZONE_NAME_RE = re.compile(r"^(.*?\bTime)\b")
_PROFILE_RE = re.compile(r"KeyName:\s*(S-[\d-]+)")
_USB_RE = re.compile(r"(?i)USBSTOR\\([^\\]+)\\([^\\]+)")


def _usb_entry(key_path: str) -> Optional[tuple[str, str, str]]:
    """``(device, serial, note)`` from a USBSTOR key path. A device's own
    serial ends at the first "&"; an instance id Windows generated
    ("7&2a8b5f7c&0", "&" second) carries no serial and is kept whole."""
    m = _USB_RE.search(key_path or "")
    if not m:
        return None
    device, instance = m.group(1), m.group(2)
    if instance[1:2] == "&":
        return device, instance, "generated by Windows, the device reports no serial"
    return device, instance.split("&")[0], ""


# ── installations ────────────────────────────────────────────────────────

def _find_config_dirs(root: Path, max_depth: int = 5) -> list[tuple[Path, bool]]:
    """``(config dir, previous)`` for every ``Windows/System32/config`` that
    holds a SYSTEM hive under ``root``; a ``Windows.old`` tree is marked
    as a previous installation."""
    out: list[tuple[Path, bool]] = []
    stack: list[tuple[Path, int]] = [(root, 0)]
    while stack:
        here, depth = stack.pop()
        try:
            entries = [e for e in os.scandir(here) if e.is_dir(follow_symlinks=False)]
        except OSError:
            continue
        for e in entries:
            low = e.name.casefold()
            if low == "config" and here.name.casefold() == "system32" and here.parent.name.casefold() in ("windows", "winnt"):
                if any(f.casefold() == "system" for f in os.listdir(e.path) if os.path.isfile(os.path.join(e.path, f))):
                    previous = any(p.casefold() == "windows.old" for p in Path(e.path).parts)
                    out.append((Path(e.path), previous))
                continue
            if depth < max_depth and low not in ("mnt", ".atlas", "analysis", "exports", "reports", "$recycle.bin", "programdata"):
                stack.append((Path(e.path), depth + 1))
    return out


def _hives(config_dir: Path) -> dict[str, str]:
    names = {f.casefold(): f for f in os.listdir(config_dir) if os.path.isfile(config_dir / f)}
    return {h: str(config_dir / names[h.casefold()]) for h in HIVES if h.casefold() in names}


def find_installations(case_dir: str | os.PathLike) -> list[dict[str, Any]]:
    """Every Windows installation under a live mount or a collected tree."""
    root = Path(case_dir).resolve()
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    try:
        from core.mount_plan import mounted_volumes
        volumes = mounted_volumes(root)
    except Exception:  # noqa: BLE001
        volumes = []
    for vol in volumes:
        mp = vol.get("mount_point")
        if not mp:
            continue
        for cfg, previous in _find_config_dirs(Path(mp), max_depth=3):
            key = str(cfg)
            if key in seen:
                continue
            seen.add(key)
            stem = str(vol.get("stem") or Path(mp).parent.name)
            out.append({"stem": stem + ("-previous" if previous else ""), "image": vol.get("path") or "",
                        "config_dir": key, "hives": _hives(cfg), "previous": previous,
                        "source": "mount", "root": str(cfg.parent.parent.parent)})
    for base in ("evidence",):
        tree = root / base
        if tree.is_dir():
            for cfg, previous in _find_config_dirs(tree, max_depth=6):
                key = str(cfg)
                if key in seen:
                    continue
                seen.add(key)
                rel = cfg.parent.parent.parent.relative_to(root).as_posix().replace("/", "_")
                out.append({"stem": rel + ("-previous" if previous else ""), "image": "",
                            "config_dir": key, "hives": _hives(cfg), "previous": previous,
                            "source": "tree", "root": str(cfg.parent.parent.parent)})
    return out


# ── reading hives ────────────────────────────────────────────────────────

def _run_recmd(case_dir: Path, hive: str, out_dir: Path, csv_name: str, *, nl: bool) -> dict[str, Any]:
    from core.executor import run_dotnet
    from tools.eztools import EZ, _resolve_ez_dll
    dll = _resolve_ez_dll(f"{EZ}/RECmd/RECmd.dll")
    args = ["-f", hive, "--bn", str(BATCH), "--csv", str(out_dir), "--csvf", csv_name]
    if nl:
        args.append("--nl")
    res = run_dotnet(dll, args, timeout=300, output_dir=str(out_dir))
    res = dict(res or {})
    res["cmd"] = "RECmd " + " ".join(args)
    return res


def _record_call(case_dir: Path, cmd: str, res: dict[str, Any], csv_path: Path) -> Optional[int]:
    """The read is a tool call in the trace, so the ledger credits the hive
    and an observation can cite it."""
    try:
        from core.execution_log import log
        ok = bool(res.get("success")) and csv_path.is_file()
        stdout = str(res.get("stdout") or "")
        # The executor recorded the run already; that call is the one cited.
        cid = res.get("_atlas_call_id") or log.record_tool_call(
            cmd=cmd, success=ok, truncated=False, retries=0,
            exit_code=int(res.get("exit_code") or (0 if ok else 1)),
            stderr=str(res.get("stderr") or "")[:2000], stdout_excerpt=stdout[:4000],
            stdout_file=str(csv_path) if csv_path.is_file() else "")
        try:
            from core.evidence_index import index_output
            if csv_path.is_file():
                index_output(cid, "ez.recmd_hive", csv_path.read_text(encoding="utf-8", errors="replace"),
                             source_path=str(csv_path))
        except Exception:  # noqa: BLE001
            pass
        return cid
    except Exception:  # noqa: BLE001 - an unconfigured log records nothing
        return None


def read_hive(case_dir: str | os.PathLike, hive: str, out_dir: str | os.PathLike, csv_name: str) -> dict[str, Any]:
    """RECmd over one hive with the baseline batch. A dirty hive whose logs
    are missing is refused by RECmd; the read is repeated with ``--nl`` and
    the state says the values may be stale."""
    root, out = Path(case_dir).resolve(), Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    csv_path = out / csv_name
    res = _run_recmd(root, hive, out, csv_name, nl=False)
    console = str(res.get("stdout") or "") + "\n" + str(res.get("stderr") or "")
    state = {"dirty": bool(re.search(r"(?i)\bdirty\b", console)),
             "logs_replayed": bool(re.search(r"(?i)replay", console)) and not re.search(r"(?i)not exist|missing", console),
             "nl_used": False, "console": [l.strip() for l in console.splitlines() if _DIRTY_RE.search(l)][:8]}
    if not csv_path.is_file() and re.search(r"(?i)dirty|transaction log", console):
        res = _run_recmd(root, hive, out, csv_name, nl=True)
        console = str(res.get("stdout") or "") + "\n" + str(res.get("stderr") or "")
        state.update({"dirty": True, "logs_replayed": False, "nl_used": True,
                      "console": state["console"] + [l.strip() for l in console.splitlines() if _DIRTY_RE.search(l)][:4]})
    cid = _record_call(root, res.get("cmd") or "RECmd", res, csv_path)
    rows: list[dict[str, str]] = []
    if csv_path.is_file():
        with open(csv_path, encoding="utf-8-sig", newline="") as fh:
            rows = [r for r in csv.DictReader(fh) if str(r.get("Deleted") or "False").strip().lower() != "true"]
    return {"rows": rows, "call_id": cid, "csv": str(csv_path), "state": state, "ok": bool(res.get("success"))}


def _key_tail(key: str) -> str:
    """The key path without the hive's root key name."""
    parts = key.split("\\")
    return "\\".join(parts[1:]) if len(parts) > 1 else key


def _current_set(rows: list[dict[str, str]]) -> str:
    for r in rows:
        if _key_tail(r.get("KeyPath", "")).casefold() == "select" and r.get("ValueName") == "Current":
            try:
                return f"ControlSet{int(r.get('ValueData') or 1):03d}"
            except ValueError:
                break
    return "ControlSet001"


def _select(rows, key_suffix: str, value_name: Optional[str] = None, *, cs: str = "") -> list[dict[str, str]]:
    suf = key_suffix.casefold()
    out = []
    for r in rows:
        tail = _key_tail(r.get("KeyPath", ""))
        low = tail.casefold()
        if cs and low.startswith("controlset") and not low.startswith(cs.casefold()):
            continue
        if not (low.endswith(suf) or f"{suf}\\" in low + "\\"):
            continue
        if value_name is not None and r.get("ValueName") != value_name:
            continue
        out.append(r)
    return out


def _value(rows, key_suffix: str, value_name: str, *, cs: str = "") -> str:
    hits = _select(rows, key_suffix, value_name, cs=cs)
    return str(hits[0].get("ValueData") or "").strip() if hits else ""


def _epoch(value: str) -> str:
    try:
        n = int(str(value).strip())
        return _dt.datetime.fromtimestamp(n, _dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC") if n > 0 else ""
    except (ValueError, OverflowError, OSError):
        return ""


def _hex_bytes(value: str) -> bytes:
    v = str(value or "").strip()
    if not v:
        return b""
    try:
        return bytes(int(x, 16) for x in re.split(r"[-\s:]+", v) if x)
    except ValueError:
        return b""


def decode_lsa_name(value: str) -> str:
    """PolPrDmN: an LSA_UNICODE_STRING (length, maximum length, then the
    buffer offset: four bytes on a 32-bit host, eight after four bytes of
    padding on a 64-bit one) and the UTF-16LE name behind it. A header
    that does not fit the data decodes to nothing, never to its bytes."""
    raw = _hex_bytes(value)
    if len(raw) < 8:
        return ""
    length, maximum, offset = struct.unpack("<HHI", raw[:8])
    if offset == 0 and len(raw) >= 16:
        offset = struct.unpack("<Q", raw[8:16])[0]
    if offset < 8 or length % 2 or length > maximum or offset + length > len(raw):
        return ""
    try:
        text = raw[offset:offset + length].decode("utf-16-le").strip("\x00").strip()
    except UnicodeDecodeError:
        return ""
    return text if text and all(c.isprintable() for c in text) else ""


def decode_sid(value: str) -> str:
    """PolPrDmS: a binary SID; empty on a workgroup machine."""
    raw = _hex_bytes(value)
    if len(raw) < 8:
        return ""
    rev, count = raw[0], raw[1]
    authority = int.from_bytes(raw[2:8], "big")
    subs = [str(struct.unpack("<I", raw[8 + 4 * i: 12 + 4 * i])[0]) for i in range(count) if 12 + 4 * i <= len(raw)]
    return "-".join(["S", str(rev), str(authority)] + subs)


def _rip(hive: str, plugin: str) -> str:
    try:
        from core.executor import run
        res = run(["rip.pl", "-r", hive, "-p", plugin], timeout=120)
        return str((res or {}).get("stdout") or "")
    except Exception:  # noqa: BLE001
        return ""


_XP_AUDIT_CATEGORIES = ("System", "Logon", "Object Access", "Privilege Use", "Process Tracking",
                        "Policy Change", "Account Management", "Directory Service Access", "Account Logon")
_AUDIT_SETTING = {0: "none", 1: "success", 2: "failure", 3: "success and failure"}


def _nt_version(version: str) -> tuple[int, int]:
    m = re.match(r"\s*(\d+)\.(\d+)", version or "")
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def _audit_policy(security_hive: str, secrows: list[dict[str, str]] = (), version: str = "") -> list[str]:
    """The audit policy. The rip.pl auditpol plugin reads the Windows 7
    and later layout only; on NT 5.x the raw PolAdtEv value is decoded
    here (nine category DWORDs after the first, 0 none, 1 success, 2
    failure, 3 both); any other version is stated as not decoded."""
    major, minor = _nt_version(version)
    if (major, minor) >= (6, 1):
        text = _rip(security_hive, "auditpol") if security_hive else ""
        lines = [l.strip() for l in text.splitlines()
                 if re.match(r"^\s*[A-Za-z][\w /]+:[\w /-]+\s{2,}(?:S/F|S|F|N)\s*$", l)][:60]
        # An absent policy line is never "no auditing": the profile says so.
        return lines or ["audit policy not decoded (the plugin returned no lines)"]
    if major == 5:
        raw = _hex_bytes(_value(secrows, "policy\\poladtev", "(default)"))
        words = struct.unpack(f"<{len(raw) // 4}I", raw[:len(raw) // 4 * 4]) if len(raw) >= 40 else ()
        if len(words) < 10:
            return ["audit policy not decoded (PolAdtEv absent or short)"]
        return [f"Auditing {'enabled' if words[0] else 'disabled'}"] + [
            f"{name}: {_AUDIT_SETTING.get(v, str(v))}" for name, v in zip(_XP_AUDIT_CATEGORIES, words[1:10])]
    return [f"audit policy not decoded for this version ({version or 'unknown'})"]


def _shutdown_time(rows, system_hive: str, cs: str) -> str:
    raw = _value(rows, "control\\windows", "ShutdownTime", cs=cs)
    b = _hex_bytes(raw) if raw and raw != "(Binary data)" else b""
    if len(b) >= 8:
        ft = struct.unpack("<Q", b[:8])[0]
        if ft:
            return (_dt.datetime(1601, 1, 1, tzinfo=_dt.timezone.utc) + _dt.timedelta(microseconds=ft // 10)).strftime("%Y-%m-%d %H:%M:%S UTC")
    m = re.search(r"(?i)ShutdownTime\s*=?\s*([\d-]+\s+[\d:]+)\s*(Z|UTC)?", _rip(system_hive, "shutdown"))
    return f"{m.group(1)} UTC" if m else ""


# ── the profile ──────────────────────────────────────────────────────────

def _profile_from_rows(inst: dict[str, Any], read: dict[str, dict[str, Any]]) -> dict[str, Any]:
    sysrows = read.get("SYSTEM", {}).get("rows") or []
    softrows = read.get("SOFTWARE", {}).get("rows") or []
    samrows = read.get("SAM", {}).get("rows") or []
    secrows = read.get("SECURITY", {}).get("rows") or []
    cs = _current_set(sysrows)
    cv = "windows nt\\currentversion"
    os_part = {
        "product_name": _value(softrows, cv, "ProductName"),
        "current_build": _value(softrows, cv, "CurrentBuild"),
        "current_version": _value(softrows, cv, "CurrentVersion"),
        "csd_version": _value(softrows, cv, "CSDVersion"),
        "edition_id": _value(softrows, cv, "EditionID"),
        "install_date": _epoch(_value(softrows, cv, "InstallDate")),
        "install_date_note": "install of this build; on Windows 10 and later the last feature update",
        "registered_owner": _value(softrows, cv, "RegisteredOwner"),
        "registered_organization": _value(softrows, cv, "RegisteredOrganization"),
        "registered_note": "text typed at setup, not an identity",
    }
    tz_key = "control\\timezoneinformation"
    zone_raw = _value(sysrows, tz_key, "TimeZoneKeyName", cs=cs) or _value(sysrows, tz_key, "StandardName", cs=cs)
    zone_m = _ZONE_NAME_RE.match(zone_raw)
    time_part = {
        "zone": zone_m.group(1) if zone_m else zone_raw,
        "zone_source": "TimeZoneKeyName" if _value(sysrows, tz_key, "TimeZoneKeyName", cs=cs) else "StandardName (XP form)",
        "bias": _value(sysrows, tz_key, "Bias", cs=cs),
        "standard_bias": _value(sysrows, tz_key, "StandardBias", cs=cs),
        "daylight_bias": _value(sysrows, tz_key, "DaylightBias", cs=cs),
        "active_time_bias": _value(sysrows, tz_key, "ActiveTimeBias", cs=cs),
        "daylight_start": _value(sysrows, tz_key, "DaylightStart", cs=cs),
        "standard_start": _value(sysrows, tz_key, "StandardStart", cs=cs),
        "basis": ["NTFS, registry and event log timestamps are UTC",
                  "FAT12/16/32 volumes and setupapi.dev.log carry the local time of the machine that wrote them",
                  "exFAT carries a UTC offset from Vista SP1 writers on",
                  "a removable volume's local time belongs to whichever machine wrote it, never assumed to be this host"],
    }
    pol_name = ""
    pol_sid = ""
    for r in _select(secrows, "policy\\polprdmn"):
        pol_name = decode_lsa_name(r.get("ValueData") or "") or pol_name
    for r in _select(secrows, "policy\\polprdms"):
        pol_sid = decode_sid(r.get("ValueData") or "") or pol_sid
    identity = {
        "computer_name": _value(sysrows, "control\\computername\\computername", "ComputerName", cs=cs),
        "hostname": _value(sysrows, "services\\tcpip\\parameters", "NV Hostname", cs=cs) or _value(sysrows, "services\\tcpip\\parameters", "Hostname", cs=cs),
        "dns_suffix": _value(sysrows, "services\\tcpip\\parameters", "Domain", cs=cs),
        "dns_suffix_note": "DNS suffix only",
        "domain": pol_name, "domain_sid": pol_sid,
        "domain_note": "LSA primary domain: the domain the machine is joined to, or its workgroup name (then without a SID)" if pol_name else "",
    }
    accounts = []
    for r in samrows:
        m = _SAM_USER_RE.search(str(r.get("ValueData") or ""))
        if not m:
            continue
        d = _SAM_DATES_RE.search(str(r.get("ValueData2") or ""))
        accounts.append({"name": m.group(1).strip(), "rid": int(m.group(2)),
                         "created": (d.group(1) or "").strip() if d else "",
                         "last_login": (d.group(2) or "").strip() if d else "",
                         "flags": str(r.get("ValueData3") or "").replace("Account flags:", "").strip()})
    profiles = []
    for r in _select(softrows, "profilelist"):
        m = _PROFILE_RE.search(str(r.get("ValueData") or ""))
        p = re.search(r"ProfileImagePath:\s*(.+)$", str(r.get("ValueData3") or ""))
        if m:
            profiles.append({"sid": m.group(1), "path": (p.group(1).strip() if p else "")})
    interfaces: dict[str, dict[str, str]] = {}
    for r in _select(sysrows, "tcpip\\parameters\\interfaces", cs=cs):
        tail = _key_tail(r.get("KeyPath", ""))
        guid = tail.rsplit("\\", 1)[-1]
        if not guid.startswith("{"):
            continue
        name = r.get("ValueName") or ""
        if name in ("IPAddress", "DhcpIPAddress", "SubnetMask", "DhcpSubnetMask", "DefaultGateway", "DhcpDefaultGateway",
                    "DhcpServer", "EnableDHCP", "LeaseObtainedTime", "LeaseTerminatesTime", "Domain", "DhcpDomain", "NameServer"):
            v = str(r.get("ValueData") or "").strip()
            if name.startswith("Lease"):
                v = _epoch(v)
            if v and v != "0.0.0.0":
                interfaces.setdefault(guid, {})[name] = v
    interfaces = {g: v for g, v in interfaces.items() if any(k in v for k in ("IPAddress", "DhcpIPAddress"))}
    net_profiles = []
    for r in _select(softrows, "networklist\\profiles"):
        if r.get("ValueName") == "ProfileName":
            net_profiles.append({"name": str(r.get("ValueData") or ""), "key": _key_tail(r.get("KeyPath", "")).rsplit("\\", 1)[-1]})
    gateway_macs = [str(r.get("ValueData") or "") for r in _select(softrows, "networklist\\signatures")
                    if r.get("ValueName") == "DefaultGatewayMac" and re.fullmatch(r"[0-9A-Fa-f]{2}([-:][0-9A-Fa-f]{2}){5}", str(r.get("ValueData") or ""))]
    usb: dict[str, dict[str, str]] = {}
    for r in _select(sysrows, "enum\\usbstor", cs=cs):
        found = _usb_entry(r.get("KeyPath", ""))
        if not found:
            continue
        device, serial, note = found
        entry = usb.setdefault(serial, {"device": device, "serial": serial, **({"serial_note": note} if note else {})})
        if r.get("ValueName") == "FriendlyName":
            entry["friendly_name"] = str(r.get("ValueData") or "")
    software = []
    for r in _select(softrows, "currentversion\\uninstall"):
        m = _UNINSTALL_RE.search(str(r.get("ValueData") or ""))
        if not m or not m.group(1).strip():
            continue
        ts = re.search(r"Timestamp:\s*([\d-]+ [\d:]+)", str(r.get("ValueData2") or ""))
        software.append({"name": m.group(1).strip(), "version": m.group(2).strip(), "publisher": m.group(3).strip(),
                         "install_date": (m.group(4) or "").strip(), "key_time": (ts.group(1) if ts else "")})
    security_hive = inst["hives"].get("SECURITY", "")
    system_hive = inst["hives"].get("SYSTEM", "")
    channels = {}
    for r in _select(sysrows, "services\\eventlog", cs=cs):
        tail = _key_tail(r.get("KeyPath", ""))
        seg = tail.split("\\")
        if len(seg) >= 4 and r.get("ValueName") in ("MaxSize", "Retention"):
            channels.setdefault(seg[3], {})[r["ValueName"]] = str(r.get("ValueData") or "")
    settings = {
        "enable_prefetcher": _value(sysrows, "prefetchparameters", "EnablePrefetcher", cs=cs),
        "ntfs_disable_last_access_update": _value(sysrows, "control\\filesystem", "NtfsDisableLastAccessUpdate", cs=cs),
        "event_log_channels": channels,
        "vss_start": _value(sysrows, "services\\vss", "Start", cs=cs),
        "audit_policy": _audit_policy(security_hive, secrows, os_part["current_version"]) if (security_hive or secrows) else [],
        "note": "what an absence of Prefetch, of 4688 events or of last-access times means",
    }
    power = {"last_shutdown": _shutdown_time(sysrows, system_hive, cs) if system_hive else ""}
    hive_state = {h: read[h]["state"] for h in read}
    stale = [h for h, st in hive_state.items() if st.get("dirty") and not st.get("logs_replayed")]
    return {
        "schema_version": "1.0", "installation": inst["stem"], "root": inst["root"], "previous": inst["previous"],
        "source": inst["source"], "image": inst["image"], "control_set": cs,
        "hives": inst["hives"], "calls": {h: read[h].get("call_id") for h in read},
        "os": os_part, "time": time_part, "identity": identity,
        "accounts": accounts, "profiles": profiles,
        "interfaces": [{"guid": g, **v} for g, v in interfaces.items()],
        "network_profiles": net_profiles, "gateway_macs": gateway_macs,
        "gateway_mac_note": "the gateway's address, never the host's",
        "usb": list(usb.values()), "software": software, "power": power, "settings": settings,
        "hive_state": hive_state,
        "confidence": "LIKELY" if stale else "CONFIRMED",
        "stale_note": (f"hives {', '.join(stale)} were dirty and their transaction logs absent; values may be stale"
                       if stale else ""),
        "taken_at": _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }


def _profile_csv(profile: dict[str, Any]) -> str:
    import io
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(["field", "value", "note", "hive", "call_id"])
    calls = profile.get("calls") or {}
    for part, hive in (("os", "SOFTWARE"), ("time", "SYSTEM"), ("identity", "SYSTEM"), ("power", "SYSTEM"), ("settings", "SYSTEM")):
        for k, v in (profile.get(part) or {}).items():
            if isinstance(v, (str, int)) and v != "" and not k.endswith("_note") and k != "basis":
                w.writerow([f"{part}.{k}", v, (profile.get(part) or {}).get(f"{k}_note", ""), hive, calls.get(hive, "")])
    for a in profile.get("accounts") or []:
        w.writerow(["accounts.local", f"{a['name']} (RID {a['rid']})", f"created {a['created']}; last login {a['last_login']}; {a['flags']}", "SAM", calls.get("SAM", "")])
    for p in profile.get("profiles") or []:
        w.writerow(["accounts.profile", p["sid"], p["path"], "SOFTWARE", calls.get("SOFTWARE", "")])
    for i in profile.get("interfaces") or []:
        w.writerow(["interfaces.adapter", i.get("IPAddress") or i.get("DhcpIPAddress"), json.dumps(i), "SYSTEM", calls.get("SYSTEM", "")])
    for u in profile.get("usb") or []:
        w.writerow(["usb.device", u["serial"], u["device"], "SYSTEM", calls.get("SYSTEM", "")])
    for s in profile.get("software") or []:
        w.writerow(["software.installed", s["name"], f"{s['version']} {s['publisher']} {s['key_time']}".strip(), "SOFTWARE", calls.get("SOFTWARE", "")])
    return out.getvalue()


