def _statements(profile: dict[str, Any], where: str) -> list[tuple[str, str, str]]:
    """``(attr, statement, hive)`` for every fact the profile holds."""
    o, t, i, p, s = profile["os"], profile["time"], profile["identity"], profile["power"], profile["settings"]
    out: list[tuple[str, str, str]] = []
    if o["product_name"]:
        build = " ".join(x for x in (o["current_version"], f"build {o['current_build']}" if o["current_build"] else "", o["csd_version"], o["edition_id"]) if x)
        # The statement carries the words a request uses ("operating system"),
        # so the part binds to the reading by the typed test.
        out.append(("os.product", f"The operating system of the installation {where} is {o['product_name']}" + (f" ({build})" if build else "") + ".", "SOFTWARE"))
    if o["install_date"]:
        out.append(("os.install_date", f"The installation {where} was installed on {o['install_date']} ({o['install_date_note']}).", "SOFTWARE"))
    if o["registered_owner"] or o["registered_organization"]:
        who = ", ".join(x for x in (o["registered_owner"], o["registered_organization"]) if x)
        out.append(("os.registered", f"The registered owner of the installation {where} reads {who} ({o['registered_note']}).", "SOFTWARE"))
    if t["zone"]:
        bias = f", bias {t['bias']} minutes" if t["bias"] else ""
        off = _utc_offset(t["active_time_bias"])
        out.append(("time.zone", f"The time zone of the installation {where} is {t['zone']} (" + _zone_offsets(t) + (f"{off} when last written; " if off else "") + f"{t['zone_source']}{bias}, active bias {t['active_time_bias'] or 'unknown'}).", "SYSTEM"))
    if i["computer_name"]:
        out.append(("identity.computer_name", f"The computer name of the installation {where} is {i['computer_name']}.", "SYSTEM"))
    if i["domain"]:
        sid = f" (SID {i['domain_sid']})" if i["domain_sid"] else " (no domain SID: a workgroup machine)"
        out.append(("identity.domain", f"The primary domain of the installation {where} is {i['domain']}{sid}.", "SECURITY"))
    if i["dns_suffix"]:
        out.append(("identity.dns_suffix", f"The DNS suffix of the installation {where} is {i['dns_suffix']} (DNS suffix only, not domain membership).", "SYSTEM"))
    if profile["accounts"]:
        names = "; ".join(f"{a['name']} (RID {a['rid']}, last login {a['last_login'] or 'never'})" for a in profile["accounts"])
        out.append(("accounts.local", f"The local accounts of the installation {where} (local accounts only) are: {names}.", "SAM"))
    if profile["profiles"]:
        names = "; ".join(f"{q['sid']} at {q['path']}" for q in profile["profiles"] if q["path"])
        out.append(("accounts.profiles", f"The profile list of the installation {where} holds: {names}.", "SOFTWARE"))
    if profile["interfaces"]:
        parts = []
        for a in profile["interfaces"]:
            addr = a.get("IPAddress") or a.get("DhcpIPAddress")
            parts.append(f"{addr}" + (f" via DHCP server {a['DhcpServer']}" if a.get("DhcpServer") else "") + (f", gateway {a.get('DefaultGateway') or a.get('DhcpDefaultGateway')}" if (a.get("DefaultGateway") or a.get("DhcpDefaultGateway")) else ""))
        out.append(("interfaces.addresses", f"The network interfaces of the installation {where} were configured with: {'; '.join(parts)}.", "SYSTEM"))
    if profile["network_profiles"]:
        out.append(("interfaces.network_profiles", f"The network profiles of the installation {where} are: {', '.join(n['name'] for n in profile['network_profiles'])}.", "SOFTWARE"))
    if profile["usb"]:
        devs = "; ".join(f"{u['device']} serial {u['serial']}" + (f" ({u['serial_note']})" if u.get("serial_note") else "")
                         for u in profile["usb"])
        out.append(("usb.devices", f"The USB storage devices recorded by the installation {where} are: {devs}.", "SYSTEM"))
    if profile["software"]:
        names = ", ".join(f"{x['name']} {x['version']}".strip() for x in profile["software"][:80])
        out.append(("software.installed", f"The installed software of the installation {where} lists: {names}.", "SOFTWARE"))
    if p["last_shutdown"]:
        out.append(("power.last_shutdown", f"The last clean shutdown of the installation {where} was at {p['last_shutdown']}.", "SYSTEM"))
    if s["enable_prefetcher"] or s["ntfs_disable_last_access_update"]:
        out.append(("settings.artifacts", f"The installation {where} has EnablePrefetcher={s['enable_prefetcher'] or 'unset'} and NtfsDisableLastAccessUpdate={s['ntfs_disable_last_access_update'] or 'unset'} ({s['note']}).", "SYSTEM"))
    if s["audit_policy"]:
        out.append(("settings.audit_policy", f"The audit policy of the installation {where} reads: {'; '.join(s['audit_policy'][:40])}.", "SECURITY"))
    return out


def record_observations(case_dir: str | os.PathLike, inst: dict[str, Any], profile: dict[str, Any]) -> list[str]:
    from core.claim_graph import add_observation, load_graph
    root = Path(case_dir).resolve()
    host = _host_label(root, inst, profile)
    where = f"under {inst['root']}" if inst["source"] == "tree" else f"on {inst['stem'].removesuffix('-previous')}"
    if inst["previous"]:
        where += " (a previous installation, Windows.old)"
    existing = {(n.get("attrs") or {}).get("baseline"): nid for nid, n in (load_graph(root).get("nodes") or {}).items()
                if isinstance(n, dict) and n.get("kind") == "observation" and (n.get("attrs") or {}).get("installation") == inst["stem"]}
    ids: list[str] = []
    calls = profile.get("calls") or {}
    for attr, statement, hive in _statements(profile, where):
        if attr in existing:
            ids.append(existing[attr])
            continue
        cid = calls.get(hive)
        hive_path = inst["hives"].get(hive, "")
        try:
            rel = str(Path(hive_path).resolve().relative_to(root)) if hive_path else ""
        except ValueError:
            rel = hive_path
        r = add_observation(root, statement, confidence=profile["confidence"],
                            evidence=[{"artifact": rel, "locator": attr, "call_id": cid}] if rel else None,
                            host=host, reasoning=profile.get("stale_note") or "system baseline, read from the hive",
                            attrs={"baseline": attr, "installation": inst["stem"], "hive": rel, "call_id": cid})
        if r.get("success"):
            ids.append(r["node_id"])
    return ids


# ── running it ───────────────────────────────────────────────────────────

def _hive_stamp(inst: dict[str, Any]) -> dict[str, float]:
    out = {}
    for h, p in inst["hives"].items():
        try:
            out[h] = os.path.getmtime(p)
        except OSError:
            out[h] = 0.0
    return out


def run_baseline(case_dir: str | os.PathLike) -> dict[str, Any]:
    """Take the baseline of every installation not profiled yet (or whose
    hives changed). Never raises; the result lists what was taken and why
    an installation was not."""
    root = Path(case_dir).resolve()
    out_root = root / OUT_DIR
    summary: dict[str, Any] = {"taken": [], "skipped": [], "errors": []}
    try:
        installs = find_installations(root)
    except Exception as e:  # noqa: BLE001
        summary["errors"].append(f"installation scan failed: {e!r}"[:200])
        return summary
    if not BATCH.is_file():
        summary["errors"].append(f"batch file missing: {BATCH}")
        return summary
    for inst in installs:
        stem = re.sub(r"[^A-Za-z0-9._-]+", "_", inst["stem"])[:80]
        json_path = out_root / f"{stem}.json"
        stamp = _hive_stamp(inst)
        if json_path.is_file():
            try:
                prior = json.loads(json_path.read_text(encoding="utf-8"))
                if prior.get("hive_stamp") == stamp:
                    summary["skipped"].append({"installation": inst["stem"], "why": "already profiled", "path": str(json_path)})
                    continue
            except (OSError, ValueError):
                pass
        if "SYSTEM" not in inst["hives"] or "SOFTWARE" not in inst["hives"]:
            summary["skipped"].append({"installation": inst["stem"], "why": "SYSTEM or SOFTWARE hive absent"})
            continue
        try:
            read = {h: read_hive(root, p, out_root / stem, f"{h}.csv") for h, p in inst["hives"].items()}
            if not (read.get("SYSTEM", {}).get("rows") or read.get("SOFTWARE", {}).get("rows")):
                why = "; ".join(f"{h}: {' '.join(r['state'].get('console') or [])[:120] or 'no rows read'}"
                                for h, r in read.items() if not r.get("rows"))
                summary["skipped"].append({"installation": inst["stem"], "why": f"hives unreadable ({why})"})
                continue
            profile = _profile_from_rows(inst, read)
            profile["hive_stamp"] = stamp
            out_root.mkdir(parents=True, exist_ok=True)
            json_path.write_text(json.dumps(profile, indent=1), encoding="utf-8")
            (out_root / f"{stem}.csv").write_text(_profile_csv(profile), encoding="utf-8")
            profile["observations"] = record_observations(root, inst, profile)
            json_path.write_text(json.dumps(profile, indent=1), encoding="utf-8")
            _register_units(root, out_root / stem, [json_path, out_root / f"{stem}.csv"])
            summary["taken"].append({"installation": inst["stem"], "path": str(json_path),
                                     "observations": len(profile["observations"]), "confidence": profile["confidence"]})
        except Exception as e:  # noqa: BLE001
            summary["errors"].append(f"{inst['stem']}: {e!r}"[:300])
    return summary


