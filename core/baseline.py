    lines.append("Time basis: NTFS, registry and event logs in UTC; FAT volumes and setupapi.dev.log in the writing "
                 "machine's local time; exFAT carries an offset from Vista SP1 on; a removable volume's local time is its writer's.")
    return "\n".join(lines) + "\n"


