            f"domain {i['domain']}" + (f" (SID {i['domain_sid']})" if i["domain_sid"] else " (workgroup)") if i["domain"] else "",
            f"time zone {t['zone']} (" + _zone_offsets(t) + (f"{off} when last written, " if off else "") + f"ActiveTimeBias {t['active_time_bias'] or '?'} min)" if t["zone"] else "",
            f"registered owner {o['registered_owner']} (typed at setup)" if o["registered_owner"] else "",
