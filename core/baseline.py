"""The system baseline: what every Windows installation in evidence states
about itself, read once from its hives and recorded as observations.

Two of three runs parsed the machine hives and never stated the operating
system, the time zone or the accounts; the report then carried "timestamps
rendered as recorded" instead of the time basis, and the analyst re-derived
facts a five-second read had already produced. The baseline runs after a
volume is mounted (or a collected tree is inventoried), once per
installation, through the same RECmd wrapper the analyst uses, with a
targeted batch (``share/.common/atlas_baseline.reb``), and writes one
profile per installation under ``analysis/baseline/``:

* os: product, build, service pack, edition, install date (on Windows 10
  and later the last feature update), registered owner and organisation
  (text typed at setup, not an identity);
* time: the zone key and biases and the time basis of each evidence class;
* identity: computer name, DNS suffix (only that), the LSA primary domain
  and its SID (decoded from the raw SECURITY values);
* accounts: the local SAM accounts (local only) and the profile list;
* interfaces: addresses, DHCP and leases per adapter, network profiles, the
  gateway MAC (the gateway's, never the host's);
* usb: USBSTOR devices with their serials; software: the uninstall entries;
* power: the last shutdown; settings: prefetcher, last-access updates,
  event log sizes and retention, shadow copies, the audit policy;
* hive_state: whether each hive was dirty and whether its logs were
  replayed; a dirty hive without logs lowers the confidence of its facts.

Values are read under the control set ``Select\\Current`` names; rows RECmd
recovered as deleted are skipped. Facts are observations (readings), never
findings: the report renders them under Scope and Evidence, the tasks may
cite them, the indicator catalog and the pivots leave them alone.
"""
